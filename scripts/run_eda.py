"""Phase 3 EDA: figures + stats tables from the local PII-free SQLite copy.

Usage (after scripts/build_sqlite.py):
    python scripts/run_eda.py
Outputs: reports/figures/*.png and reports/phase3_eda_stats.md
"""
from __future__ import annotations

import sqlite3
from contextlib import closing
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from matplotlib.patches import Patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ficzon import eda  # noqa: E402
from ficzon.data import REPO_ROOT, load_config  # noqa: E402

FIG_DIR = REPO_ROOT / "reports" / "figures"


def load() -> pd.DataFrame:
    cfg = load_config()
    with closing(sqlite3.connect(str(REPO_ROOT / cfg['paths']['sqlite_db']))) as con:
        df = pd.read_sql_query("SELECT * FROM leads", con, parse_dates=["Created"])
    df["month"] = df["Created"].dt.strftime("%Y-%m")
    df["Product"] = df["Product_ID"].map(lambda v: f"Product {int(v)}" if pd.notna(v) else None)
    return df, cfg


def save(fig, name: str) -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG_DIR / name, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    eda.apply_style()
    df, cfg = load()
    overall = df.target_high.mean()
    high_set = set(cfg["target"]["high_potential"])
    md = ["# Phase 3 EDA statistics", "",
          "_Generated by `scripts/run_eda.py`. Rates are High Potential share (Open mapped to Low). "
          "Intervals are 95% Wilson. Aggregates only._", "",
          f"Overall High Potential rate: **{overall*100:.2f}%** ({df.target_high.sum():,} of {len(df):,})", ""]

    # fig01 status distribution
    sc = df.Status.value_counts().sort_values()
    fig, ax = plt.subplots(figsize=(8, 4.6))
    ax.barh(sc.index, sc.values, color=[eda.BLUE if s in high_set else eda.GRAY for s in sc.index], height=0.62, zorder=2)
    for i, v in enumerate(sc.values):
        ax.text(v + 25, i, f"{v:,}  ({v/len(df)*100:.1f}%)", va="center", fontsize=8.5, color=eda.INK_2)
    ax.set_xlim(0, sc.max() * 1.25); ax.grid(axis="y", visible=False)
    ax.set_xlabel("Leads"); ax.set_title("Status distribution and working target mapping")
    ax.legend(handles=[Patch(color=eda.BLUE, label="High Potential (working mapping)"),
                       Patch(color=eda.GRAY, label="Low Potential (incl. Open)")], loc="lower right", frameon=False, fontsize=8.5)
    save(fig, "fig01_status_distribution.png")
    md += ["## Status counts", "", sc.sort_values(ascending=False).rename("n").to_frame().to_markdown(), ""]

    # fig02 monthly trend (three panels, shared x; no dual axis)
    m = eda.rate_table(df, "month")
    m["pct_open"] = df.groupby("month").Status.apply(lambda s: (s == "Open").mean()).values
    fig, axes = plt.subplots(3, 1, figsize=(8.5, 7.2), sharex=True, gridspec_kw={"height_ratios": [1, 1.2, 0.8]})
    x = np.arange(len(m))
    axes[0].bar(x, m.n, color=eda.GRAY, width=0.62, zorder=2); axes[0].set_ylabel("Leads")
    axes[0].set_title("Lead volume, High Potential rate and Open share by creation month")
    for xi, n in zip(x, m.n): axes[0].text(xi, n + 20, f"{n:,}", ha="center", fontsize=8, color=eda.INK_2)
    axes[1].fill_between(x, m.lo * 100, m.hi * 100, color=eda.BLUE_SOFT, alpha=0.5, lw=0, label="95% interval")
    axes[1].plot(x, m.rate * 100, color=eda.BLUE, lw=2, marker="o", ms=5, label="High Potential rate")
    axes[1].axhline(overall * 100, color=eda.GRAY, ls="--", lw=1.2, label=f"Overall {overall*100:.1f}%")
    axes[1].set_ylabel("High Potential (%)"); axes[1].legend(frameon=False, fontsize=8, loc="upper left")
    axes[2].plot(x, m.pct_open * 100, color=eda.INK_2, lw=2, marker="o", ms=5); axes[2].set_ylabel("Still 'Open' (%)")
    labels = [f"{mm[5:]}/{mm[2:4]}" + ("*" if mm in ("2018-04", "2018-11") else "") for mm in m.month]
    axes[2].set_xticks(x); axes[2].set_xticklabels(labels)
    axes[2].set_xlabel("Creation month (* partial: data starts 28 Apr, ends 14 Nov)")
    save(fig, "fig02_monthly_trend.png")
    md += ["## Monthly", "", m.assign(rate=(m.rate*100).round(1), lo=(m.lo*100).round(1), hi=(m.hi*100).round(1),
                                    pct_open=(m.pct_open*100).round(1)).to_markdown(index=False), ""]

    # fig03-07 categorical breakdowns
    specs = [("Source", "fig03_by_source.png", "High Potential rate by lead source", (8.5, 7.6)),
             ("Location", "fig04_by_location.png", "High Potential rate by location", (8.5, 6.4)),
             ("Delivery_Mode", "fig05_by_delivery_mode.png", "High Potential rate by delivery mode", (8.5, 3.6)),
             ("Sales_Agent", "fig06_by_sales_agent.png", "High Potential rate by sales agent", (8.5, 5.8)),
             ("Product", "fig07_by_product.png", "High Potential rate by product", (8.5, 6.4))]
    grouped = {}
    for col, fname, title, size in specs:
        g = eda.group_levels(df[col], 30)
        grouped[col] = g
        t = eda.rate_table(df.assign(_g=g), "_g").rename(columns={"_g": col})
        fig, ax = plt.subplots(figsize=size)
        eda.barh_rate(ax, t, col, overall, title, "Levels under 30 rows are folded into 'Other'; missing values shown explicitly")
        save(fig, fname)
        md += [f"## {col}", "", t.assign(rate=(t.rate*100).round(1), lo=(t.lo*100).round(1), hi=(t.hi*100).round(1))
               .sort_values("n", ascending=False).to_markdown(index=False), ""]

    # fig08 missingness / data-entry signals
    rows = []
    for name, mask in [("Product_ID missing", df.Product_ID.isna()), ("Source missing", df.Source.isna()),
                       ("Sales_Agent missing", df.Sales_Agent.isna()), ("Location missing", df.Location.isna()),
                       ("Mobile missing", df.mobile_missing == 1), ("Email not valid", df.email_valid == 0)]:
        for flag, sub in [("Yes", df[mask]), ("No", df[~mask])]:
            rows.append({"signal": name, "present": flag, "n": len(sub), "k": int(sub.target_high.sum())})
    s = pd.DataFrame(rows); s["rate"] = s.k / s.n; s["lo"], s["hi"] = eda.wilson(s.k, s.n)
    fig, ax = plt.subplots(figsize=(8.5, 5.4))
    names = list(dict.fromkeys(s.signal)); ypos = np.arange(len(names))[::-1]
    for yi, nm in zip(ypos, names):
        for off, flag, col in [(0.17, "Yes", eda.BLUE), (-0.17, "No", eda.GRAY)]:
            r = s[(s.signal == nm) & (s.present == flag)].iloc[0]
            ax.barh(yi + off, r.rate * 100, height=0.3, color=col, zorder=2)
            ax.errorbar(r.rate * 100, yi + off, xerr=[[(r.rate - r.lo) * 100], [(r.hi - r.rate) * 100]], fmt="none", ecolor=eda.INK_2, elinewidth=1, capsize=2, zorder=3)
            ax.text(r.hi * 100 + 1.2, yi + off, f"{r.rate*100:.1f}%  (n={r.n:,})", va="center", fontsize=8, color=eda.INK_2)
    ax.axvline(overall * 100, color=eda.GRAY, ls="--", lw=1.2)
    ax.set_yticks(ypos); ax.set_yticklabels(names); ax.set_xlim(0, 100); ax.grid(axis="y", visible=False)
    ax.set_xlabel("High Potential rate (%)  -  whiskers: 95% interval")
    ax.set_title("Data-completeness signals vs High Potential rate")
    ax.legend(handles=[Patch(color=eda.BLUE, label="Condition true"), Patch(color=eda.GRAY, label="Condition false")], frameon=False, fontsize=8.5, loc="lower right")
    save(fig, "fig08_missingness_signals.png")
    md += ["## Completeness signals", "", s.assign(rate=(s.rate*100).round(1), lo=(s.lo*100).round(1), hi=(s.hi*100).round(1)).to_markdown(index=False), ""]

    # fig09 Source x Delivery_Mode heatmap (cells with n>=30 only)
    big_src = df.Source.value_counts()[lambda v: v >= 200].index
    h = df[df.Source.isin(big_src) & df.Delivery_Mode.isin(["Mode-1", "Mode-3", "Mode-5"])]
    piv = h.pivot_table(index="Source", columns="Delivery_Mode", values="target_high", aggfunc=["mean", "size"])
    rate, cnt = piv["mean"] * 100, piv["size"]
    rate = rate.where(cnt >= 30)
    order = cnt.sum(axis=1).sort_values(ascending=False).index
    rate, cnt = rate.loc[order], cnt.loc[order]
    annot = rate.round(0).astype("Int64").astype(str).radd("") + "%\nn=" + cnt.astype(int).map("{:,}".format)
    fig, ax = plt.subplots(figsize=(7.6, 4.8))
    sns.heatmap(rate, annot=annot.where(rate.notna(), ""), fmt="", cmap=eda.SEQ, vmin=0, vmax=70, cbar_kws={"label": "High Potential rate (%)"},
                linewidths=2, linecolor=eda.SURFACE, ax=ax, annot_kws={"fontsize": 8.5})
    ax.set_title("High Potential rate: source x delivery mode"); ax.set_xlabel(""); ax.set_ylabel(""); ax.grid(False)
    save(fig, "fig09_source_by_mode_heatmap.png")
    md += ["## Source x Delivery_Mode (cells n>=30)", "", rate.round(1).to_markdown(), "", "Cell sizes:", "", cnt.to_markdown(), ""]

    # fig10 within-source monthly trend (full months only) + mode mix by month
    full = df[df.month.between("2018-05", "2018-10")]
    top3 = ["Call", "Live Chat-Direct", "Website"]
    fig, ax = plt.subplots(figsize=(8.2, 4.6))
    ms = sorted(full.month.unique()); xs = np.arange(len(ms)); lines = []
    for src, col in zip(top3, [eda.BLUE, eda.ORANGE, eda.AQUA]):
        r = full[full.Source == src].groupby("month").target_high.agg(["size", "mean"]).reindex(ms)
        ax.plot(xs, r["mean"] * 100, color=col, lw=2, marker="o", ms=5, label=src)
        ax.text(xs[-1] + 0.08, r["mean"].iloc[-1] * 100, src, color=eda.INK, fontsize=8.5, va="center")
        lines.append(r.assign(source=src, rate=(r["mean"] * 100).round(1)).reset_index()[["source", "month", "size", "rate"]])
    ax.axhline(overall * 100, color=eda.GRAY, ls="--", lw=1.2)
    ax.set_xticks(xs); ax.set_xticklabels([f"{mm[5:]}/{mm[2:4]}" for mm in ms]); ax.set_xlim(-0.2, len(ms) + 0.9)
    ax.set_ylabel("High Potential rate (%)"); ax.set_xlabel("Creation month (full months only)")
    ax.set_title("Is the late-2018 rise within each source, or a mix shift?"); ax.legend(frameon=False, fontsize=8.5, loc="upper left")
    save(fig, "fig10_within_source_trend.png")
    mode_mix = pd.crosstab(df.month, df.Delivery_Mode, normalize="index").mul(100).round(1)
    md += ["## Within-source monthly High rate (May-Oct)", "", pd.concat(lines).to_markdown(index=False), "",
           "## Delivery_Mode share of leads by month (%)", "", mode_mix.to_markdown(), ""]

    # fig12 within-mode monthly trend (controls for the Delivery_Mode mix shift)
    fig, ax = plt.subplots(figsize=(8.2, 4.6)); rows = []
    for mode, col in zip(["Mode-1", "Mode-3", "Mode-5"], [eda.BLUE, eda.ORANGE, eda.AQUA]):
        r = full[full.Delivery_Mode == mode].groupby("month").target_high.agg(["size", "mean"]).reindex(ms)
        ax.plot(xs, r["mean"] * 100, color=col, lw=2, marker="o", ms=5, label=mode)
        ax.text(xs[-1] + 0.08, r["mean"].iloc[-1] * 100, mode, color=eda.INK, fontsize=8.5, va="center")
        rows.append(r.assign(mode=mode, rate=(r["mean"] * 100).round(1)).reset_index()[["mode", "month", "size", "rate"]])
    ax.axhline(overall * 100, color=eda.GRAY, ls="--", lw=1.2)
    ax.set_xticks(xs); ax.set_xticklabels([f"{mm[5:]}/{mm[2:4]}" for mm in ms]); ax.set_xlim(-0.2, len(ms) + 0.9)
    ax.set_ylabel("High Potential rate (%)"); ax.set_xlabel("Creation month (full months only)")
    ax.set_title("High Potential rate by month within each delivery mode"); ax.legend(frameon=False, fontsize=8.5, loc="upper left")
    save(fig, "fig12_within_mode_trend.png")
    md += ["## Within-mode monthly High rate (May-Oct)", "", pd.concat(rows).to_markdown(index=False), ""]

    # fig11 association strength
    feats = {"Source": grouped["Source"], "Location": grouped["Location"], "Delivery_Mode": df.Delivery_Mode,
             "Sales_Agent": grouped["Sales_Agent"], "Product": grouped["Product"], "Creation month": df.month,
             "Email valid": df.email_valid, "Mobile missing": df.mobile_missing}
    v = pd.Series({k: eda.cramers_v(s_, df.target_high) for k, s_ in feats.items()}).sort_values()
    fig, ax = plt.subplots(figsize=(7.4, 4.2))
    ax.barh(v.index, v.values, color=eda.BLUE, height=0.6, zorder=2)
    for i, val in enumerate(v.values): ax.text(val + 0.005, i, f"{val:.2f}", va="center", fontsize=8.5, color=eda.INK_2)
    ax.set_xlim(0, v.max() * 1.2); ax.grid(axis="y", visible=False)
    ax.set_xlabel("Bias-corrected Cramer's V with High Potential (0 = none, 1 = perfect)")
    ax.set_title("Association strength with the target (not causal)")
    save(fig, "fig11_association_strength.png")
    md += ["## Cramer's V (bias-corrected)", "", v.sort_values(ascending=False).round(3).rename("V").to_frame().to_markdown(), ""]

    # fig22 label maturity: status groups by creation month (100% stacked)
    groups = {"CONVERTED": ["CONVERTED"], "Potential / In Progress Positive": ["Potential", "In Progress Positive"],
              "Long Term / LOST": ["Long Term", "LOST"], "Junk / Not Responding / Just Enquiry": ["Junk Lead", "Not Responding", "Just Enquiry"],
              "In Progress Negative / Open": ["In Progress Negative", "Open"]}
    gcol = {"CONVERTED": eda.BLUE, "Potential / In Progress Positive": eda.AQUA, "Long Term / LOST": eda.ORANGE,
            "Junk / Not Responding / Just Enquiry": eda.GRAY, "In Progress Negative / Open": "#e87ba4"}
    mix = pd.DataFrame({g: df.assign(_in=df.Status.isin(s)).groupby("month")._in.mean() * 100 for g, s in groups.items()})
    fig, ax = plt.subplots(figsize=(9, 5)); bottom = np.zeros(len(mix)); xs = np.arange(len(mix))
    for g in groups:
        ax.bar(xs, mix[g], bottom=bottom, color=gcol[g], width=0.7, edgecolor=eda.SURFACE, linewidth=1.5, label=g, zorder=2)
        for xi, (b, v) in enumerate(zip(bottom, mix[g])):
            if v >= 6: ax.text(xi, b + v / 2, f"{v:.0f}", ha="center", va="center", fontsize=8.5, color="white" if g in ("CONVERTED", "Junk / Not Responding / Just Enquiry") else eda.INK)
        bottom += mix[g].to_numpy()
    ax.set_xticks(xs); ax.set_xticklabels([f"{m[5:]}/{m[2:4]}" + ("*" if m in ("2018-04", "2018-11") else "") for m in mix.index])
    ax.set_ylim(0, 100); ax.set_ylabel("Share of leads created that month (%)"); ax.set_xlabel("Creation month (* partial)")
    ax.set_title("Statuses mature with age: older leads resolve, recent ones are still in flight"); ax.grid(axis="x", visible=False)
    ax.legend(frameon=False, fontsize=8.5, loc="upper center", bbox_to_anchor=(0.5, -0.14), ncol=3)
    save(fig, "fig22_status_maturity_by_month.png")
    md += ["## Status groups by creation month (%)", "", mix.round(1).to_markdown(), ""]

    (REPO_ROOT / "reports" / "phase3_eda_stats.md").write_text("\n".join(md), encoding="utf-8")
    print("figures:", sorted(p.name for p in FIG_DIR.glob("*.png")))


if __name__ == "__main__":
    main()
