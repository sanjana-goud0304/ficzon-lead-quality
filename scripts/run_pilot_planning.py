"""Phase 7 support: descriptive numbers for the pilot design.

Uses the out-of-time scores of the frozen models on the TEST months (descriptive only; nothing here
changes a model or threshold). Also computes planning sample sizes from the observed test-period
base rates and lead volume. Sample sizes are planning arithmetic under stated assumptions, NOT results.

Usage:  python scripts/run_pilot_planning.py
"""
from __future__ import annotations

import json
import sqlite3
from contextlib import closing
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import norm

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ficzon.cleaning import clean_leads  # noqa: E402
from ficzon.data import REPO_ROOT, load_config  # noqa: E402
from ficzon.features import add_features  # noqa: E402
from ficzon.scoring import build_scores  # noqa: E402

warnings.filterwarnings("ignore")


def n_per_arm(p1: float, p2: float, alpha: float = 0.05, power: float = 0.8) -> int:
    """Two-sided two-proportion z-test sample size per arm (normal approximation, no clustering)."""
    za, zb = norm.ppf(1 - alpha / 2), norm.ppf(power)
    pbar = (p1 + p2) / 2
    num = (za * np.sqrt(2 * pbar * (1 - pbar)) + zb * np.sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2
    return int(np.ceil(num / (p1 - p2) ** 2))


def main() -> None:
    cfg = load_config()
    frozen = json.loads((REPO_ROOT / "reports" / "phase6_frozen_config.json").read_text(encoding="utf-8"))
    with closing(sqlite3.connect(str(REPO_ROOT / cfg['paths']['sqlite_db']))) as con:
        df = pd.read_sql_query("SELECT * FROM leads", con, parse_dates=["Created"])
    df = add_features(clean_leads(df, cfg)).sort_values(["Created", "lead_id"]).reset_index(drop=True)
    sc = build_scores(df, frozen, cfg)
    d = df.merge(sc, on="lead_id")
    d["is_converted"] = (d["Status"] == "CONVERTED").astype(int)
    test = d[d.score_source == "final_model"].copy()
    dev = d[d.Created <= pd.Timestamp(cfg["split"]["val_end"])]
    days = (test.Created.max().normalize() - test.Created.min().normalize()).days + 1
    leads_per_week = len(test) / days * 7

    md = ["# Phase 7 support: pilot planning numbers", "",
          "_Generated by `scripts/run_pilot_planning.py`. Descriptive statistics on the test months (Oct 1 - Nov 14, 2018) using out-of-time scores; "
          "no model or threshold was changed using them._", "",
          f"- Test leads: {len(test):,} over {days} days = {leads_per_week:.0f} leads/week",
          f"- High Potential rate {test.target_high.mean()*100:.1f}%; CONVERTED rate {test.is_converted.mean()*100:.1f}% ({int(test.is_converted.sum())} leads)", ""]

    # 1. score-bucket tables
    for name in ["post_contact", "assignment_time"]:
        col = f"score_{name}"
        order = test.sort_values([col, "lead_id"], ascending=[False, True]).reset_index(drop=True)
        order["bucket"] = pd.cut(np.arange(len(order)), bins=5, labels=[f"Q{i} ({'top' if i == 1 else 'bottom' if i == 5 else 'mid'})" for i in range(1, 6)])
        t = order.groupby("bucket", observed=True).agg(leads=("lead_id", "size"), high_rate=("target_high", "mean"), converted_rate=("is_converted", "mean"),
                                                       high=("target_high", "sum"), converted=("is_converted", "sum")).reset_index()
        t["share_of_all_high_%"] = t.high / t.high.sum() * 100; t["share_of_all_converted_%"] = t.converted / t.converted.sum() * 100
        t[["high_rate", "converted_rate"]] *= 100
        md += [f"## Score quintiles: {name} model (test months)", "", t.drop(columns=["high", "converted"]).round(1).to_markdown(index=False), ""]
        cap = []
        for lab, sel in [("Top 20%", order.index < round(0.2 * len(order))), ("Top 40%", order.index < round(0.4 * len(order))),
                         ("Bottom 40%", order.index >= len(order) - round(0.4 * len(order)))]:
            s = order[sel]
            cap.append({"group": lab, "leads": len(s), "share_of_High_%": s.target_high.sum() / order.target_high.sum() * 100,
                        "share_of_CONVERTED_%": s.is_converted.sum() / order.is_converted.sum() * 100})
        md += [f"Share of outcomes held by score groups ({name}):", "", pd.DataFrame(cap).round(1).to_markdown(index=False), ""]

    # 2. simple segment rule defined from train+validation only
    seg_dev = dev.assign(low_seg=(dev.Product == "P15") | (dev.Location == "Other Locations"))
    seg_test = test.assign(low_seg=(test.Product == "P15") | (test.Location == "Other Locations"))
    rows = []
    for lab, x in [("train+validation", seg_dev), ("test", seg_test)]:
        f = x[x.low_seg]; g = x[~x.low_seg]
        rows.append({"period": lab, "flagged_share_of_leads_%": len(f) / len(x) * 100, "High_rate_flagged_%": f.target_high.mean() * 100,
                     "High_rate_not_flagged_%": g.target_high.mean() * 100, "share_of_all_High_in_flagged_%": f.target_high.sum() / x.target_high.sum() * 100,
                     "CONVERTED_rate_flagged_%": (f.Status == "CONVERTED").mean() * 100, "share_of_all_CONVERTED_in_flagged_%": (f.Status == "CONVERTED").sum() / (x.Status == "CONVERTED").sum() * 100})
    md += ["## Simple segment rule (no model): Product P15 or Location 'Other Locations'", "",
           "Rule chosen from the Phase 3 EDA on train+validation data; applied unchanged to the test months.", "",
           pd.DataFrame(rows).round(1).to_markdown(index=False), ""]

    # 3. planning sample sizes
    p_conv, p_high = test.is_converted.mean(), test.target_high.mean()
    plan = []
    for label, p1, uplifts in [("CONVERTED rate", p_conv, [("+20% relative", p_conv * 1.2), ("+30% relative", p_conv * 1.3), ("+50% relative", p_conv * 1.5)]),
                               ("High Potential rate", p_high, [("+3 pp", p_high + .03), ("+5 pp", p_high + .05), ("+8 pp", p_high + .08)])]:
        for lab, p2 in uplifts:
            n = n_per_arm(p1, p2)
            plan.append({"outcome": label, "baseline_%": p1 * 100, "target_effect": lab, "target_%": p2 * 100, "leads_per_arm": n,
                         "weeks_at_50/50_split": 2 * n / leads_per_week})
    md += ["## Planning sample sizes (two-arm, lead-level randomization)", "",
           "Assumptions: two-sided alpha 0.05, power 80%, normal approximation, baselines and lead volume from the test months, "
           "leads independent. Real leads are clustered by contact and agent, so these are lower bounds; add the time needed for outcomes to mature.", "",
           pd.DataFrame(plan).round(1).to_markdown(index=False), ""]
    (REPO_ROOT / "reports" / "phase7_pilot_planning.md").write_text("\n".join(md), encoding="utf-8")
    pd.DataFrame(plan).to_csv(REPO_ROOT / "reports" / "phase7_sample_size_plan.csv", index=False)
    print("\n".join(md))


if __name__ == "__main__":
    main()
