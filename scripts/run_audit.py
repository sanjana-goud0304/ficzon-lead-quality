"""Run every named query in a .sql file against the local SQLite DB and write markdown.

Usage:
    python scripts/run_audit.py sql/01_data_audit.sql reports/phase2_audit_results.md
"""
from __future__ import annotations

import re
import sqlite3
from contextlib import closing
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ficzon.data import REPO_ROOT, load_config  # noqa: E402
from ficzon.sqlutil import parse_queries  # noqa: E402


def main(sql_file: str, out_file: str) -> None:
    cfg = load_config()
    db = REPO_ROOT / cfg["paths"]["sqlite_db"]
    queries = parse_queries(Path(sql_file).read_text(encoding="utf-8"))
    lines = ["# Phase 2 SQL audit results", "",
             "_Generated by `scripts/run_audit.py` from the local PII-free SQLite copy. Aggregates only._", ""]
    with closing(sqlite3.connect(str(db))) as con:
        for name, q in queries:
            df = pd.read_sql_query(q, con)
            lines += [f"## {name}", "", df.to_markdown(index=False), ""]
    Path(out_file).parent.mkdir(parents=True, exist_ok=True)
    Path(out_file).write_text("\n".join(lines), encoding="utf-8")
    print(f"Ran {len(queries)} queries -> {out_file}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
