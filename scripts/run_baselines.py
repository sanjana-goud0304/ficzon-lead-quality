"""Phase 5: fit baselines and candidate models on TRAIN, score VALIDATION (September).

No hyperparameter tuning and no use of the test months (asserted). Phase 6 does
time-ordered CV, tuning and the single final test evaluation.

Usage:  python scripts/run_baselines.py
Output: reports/phase5_model_comparison.md, reports/figures/fig15_model_comparison.png
"""
from __future__ import annotations

import sqlite3
from contextlib import closing
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ficzon import eda  # noqa: E402
from ficzon.cleaning import clean_leads  # noqa: E402
from ficzon.data import REPO_ROOT, load_config  # noqa: E402
from ficzon.evaluate import evaluate_scores  # noqa: E402
from ficzon.features import FEATURE_SETS, add_features  # noqa: E402
from ficzon.models import build_baselines, build_candidates  # noqa: E402
from ficzon.splits import temporal_masks  # noqa: E402

warnings.filterwarnings("ignore")


def main() -> None:
    cfg = load_config(); seed = cfg["random_seed"]
    with closing(sqlite3.connect(str(REPO_ROOT / cfg['paths']['sqlite_db']))) as con:
        df = pd.read_sql_query("SELECT * FROM leads", con, parse_dates=["Created"])
    df = add_features(clean_leads(df, cfg))
    masks = temporal_masks(df["Created"], cfg)
    dev = df[masks["train"] | masks["val"]]                      # test rows removed before any fitting
    assert dev["Created"].max() <= pd.Timestamp(cfg["split"]["val_end"])
    tr = dev[masks["train"].loc[dev.index]]; va = dev[masks["val"].loc[dev.index]]
    ytr, yva = tr["target_high"].to_numpy(), va["target_high"].to_numpy()

    rows = []
    def run(name, fset_label, pipe, cols):
        pipe.fit(tr[cols], ytr)
        score = pipe.predict_proba(va[cols])[:, 1]
        m = evaluate_scores(yva, score, 0.2, seed)
        rows.append({"model": name, "feature_set": fset_label, **m})

    for name, pipe in build_baselines().items():
        run(name, "n/a (Source only)" if "rule" in name else "n/a", pipe, ["Source_clean"])
    for fset, cols in FEATURE_SETS.items():
        for name, pipe in build_candidates(cols, cfg["min_category_count"], seed).items():
            run(name, fset, pipe, cols)

    res = pd.DataFrame(rows)
    show = res.assign(**{"roc_auc (95% CI)": res.apply(lambda r: f"{r.roc_auc:.3f} ({r.roc_lo:.3f}-{r.roc_hi:.3f})", axis=1),
                         "pr_auc (95% CI)": res.apply(lambda r: f"{r.pr_auc:.3f} ({r.pr_lo:.3f}-{r.pr_hi:.3f})", axis=1)})
    show = show[["model", "feature_set", "roc_auc (95% CI)", "pr_auc (95% CI)", "precision_at_k", "recall_at_k", "lift_at_k"]]
    show = show.rename(columns={"precision_at_k": "precision@top20%", "recall_at_k": "recall@top20%", "lift_at_k": "lift@top20%"})
    md = ["# Phase 5: baselines and candidate models", "",
          "_Generated by `scripts/run_baselines.py`. Fit on train (to 31 Aug 2018), scored on validation (September 2018). "
          "Fixed default hyperparameters, no tuning. Test months untouched._", "",
          f"- Train: {len(tr):,} leads, High rate {ytr.mean()*100:.1f}%", f"- Validation: {len(va):,} leads, High rate {yva.mean()*100:.1f}% "
          f"(random-scorer PR-AUC and precision@top20% both equal this; random lift = 1.0)", "",
          "Feature sets: `creation_time` = source + creation time; `post_contact` adds Product, Location, "
          "Delivery_Mode, email_valid (timing unconfirmed, see Phase 4).", "",
          show.round(3).to_markdown(index=False), "",
          "Intervals are 95% bootstrap over validation rows. Validation is one month, so differences smaller than the intervals "
          "should not be read as a ranking.", ""]
    cs = res[res.feature_set == "creation_time"]; ex = res[res.feature_set == "post_contact"]
    rule = res[res.model == "Source-rate rule"].iloc[0]
    best_cs = cs.loc[cs.roc_auc.idxmax()]
    overlap = best_cs.roc_lo <= rule.roc_hi
    ex_overlap = (ex.roc_lo.max() <= ex.roc_hi.min())
    md += ["## Reading the results", "",
           f"- Best creation_time model ({best_cs.model}) has ROC-AUC {best_cs.roc_auc:.3f} versus {rule.roc_auc:.3f} for the Source-rate rule; "
           f"their 95% intervals {'overlap' if overlap else 'do not overlap'}. "
           f"{'The creation-safe features do not clearly beat a one-column source lookup.' if overlap else 'The creation-safe models beat the source lookup.'}",
           f"- The three extended models have ROC-AUC {ex.roc_auc.min():.3f}-{ex.roc_auc.max():.3f}; their intervals "
           f"{'all overlap, so the model type does not matter much here' if ex_overlap else 'do not all overlap'}.",
           "- Extended-set performance depends on Product, Location and Delivery_Mode being known at lead creation (unconfirmed).",
           "- Validation is a single month, and model choice made on it is provisional until Phase 6.", ""]
    (REPO_ROOT / "reports" / "phase5_model_comparison.md").write_text("\n".join(md), encoding="utf-8")
    res.to_csv(REPO_ROOT / "reports" / "phase5_model_comparison.csv", index=False)

    # Figure: ROC-AUC with CI by model and feature set
    eda.apply_style()
    order = ["Majority class (prior)", "Source-rate rule", "Logistic regression", "Random forest", "Gradient boosting"]
    fig, ax = plt.subplots(figsize=(8.8, 4.8)); ypos = {m: i for i, m in enumerate(order[::-1])}
    for fset, col, off in [("creation_time", eda.GRAY, 0.17), ("post_contact", eda.BLUE, -0.17)]:
        s = res[res.feature_set == fset]
        ax.errorbar(s.roc_auc, [ypos[m] + off for m in s.model], xerr=[s.roc_auc - s.roc_lo, s.roc_hi - s.roc_auc], fmt="o", color=col,
                    ecolor=eda.INK_2, capsize=3, ms=6, label=fset.replace("_", " "))
    b = res[res.feature_set.str.startswith("n/a")]
    ax.errorbar(b.roc_auc, [ypos[m] for m in b.model], xerr=[b.roc_auc - b.roc_lo, b.roc_hi - b.roc_auc], fmt="s", color=eda.ORANGE,
                ecolor=eda.INK_2, capsize=3, ms=6, label="baseline (no feature set)")
    ax.axvline(0.5, color=eda.GRAY, ls="--", lw=1.2); ax.set_yticks(list(ypos.values())); ax.set_yticklabels(list(ypos.keys()))
    ax.set_xlabel("Validation ROC-AUC (September)  -  whiskers: 95% bootstrap interval; dashed = random")
    ax.set_title("Model comparison on the validation month (no tuning)"); ax.grid(axis="y", visible=False)
    ax.legend(frameon=False, fontsize=8.5, loc="upper right")
    fig.savefig(REPO_ROOT / "reports/figures/fig15_model_comparison.png", bbox_inches="tight"); plt.close(fig)
    print(show.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
