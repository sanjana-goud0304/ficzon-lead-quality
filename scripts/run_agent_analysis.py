"""Segment-adjusted agent comparison on TRAIN + VALIDATION months only (test months never loaded).

Strata = Delivery_Mode x Location (rare levels pooled) x creation month, since the owner says
agents were routed on mode and delivery location and the routing changed over time.

Usage:  python scripts/run_agent_analysis.py
Output: reports/phase6c_agent_analysis.md, reports/figures/fig21_agent_adjusted_gaps.png
"""
from __future__ import annotations

import sqlite3
from contextlib import closing
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ficzon import eda  # noqa: E402
from ficzon.agents import adjusted_agent_gaps  # noqa: E402
from ficzon.cleaning import clean_leads  # noqa: E402
from ficzon.data import REPO_ROOT, load_config  # noqa: E402

warnings.filterwarnings("ignore")
MIN_COMPARABLE_FOR_PLOT = 150


def main() -> None:
    cfg = load_config()
    with closing(sqlite3.connect(str(REPO_ROOT / cfg['paths']['sqlite_db']))) as con:
        df = pd.read_sql_query("SELECT * FROM leads WHERE Created <= ?", con, params=[cfg["split"]["val_end"]], parse_dates=["Created"])
    assert df["Created"].max() <= pd.Timestamp(cfg["split"]["val_end"])
    df = clean_leads(df, cfg)
    df["month"] = df["Created"].dt.strftime("%Y-%m")
    df["Location_g"] = eda.group_levels(df["Location"], 30); df["Mode_g"] = eda.group_levels(df["Delivery_Mode"], 30)
    strata = ["Mode_g", "Location_g", "month"]

    all_ = adjusted_agent_gaps(df, strata)
    sep = adjusted_agent_gaps(df[df.month == "2018-09"], strata)
    # Robustness: gaps are peer-relative, so a large outlier agent shifts everyone else's benchmark.
    top_agent = all_.dropna(subset=["gap_pp"]).sort_values("gap_pp").iloc[-1]["agent"]
    no_top = adjusted_agent_gaps(df[df.Sales_Agent != top_agent], strata)
    jja = adjusted_agent_gaps(df[df.month.isin(["2018-06", "2018-07", "2018-08"])], strata)

    cols = ["agent", "n_leads", "n_comparable", "comparable_%", "unadjusted_high_%", "observed_%", "expected_%", "gap_pp", "gap_lo", "gap_hi"]
    md = ["# Phase 6c: agent comparison within comparable segments", "",
          "_Generated by `scripts/run_agent_analysis.py`. Train + validation months only (Apr-Sep 2018)._", "",
          "Each lead is compared with other agents' leads in the same Delivery_Mode x Location x month stratum (leave-agent-out). "
          "`gap_pp` = observed High rate minus the rate expected from those peers, in percentage points, with a 95% bootstrap interval. "
          "Leads in strata with fewer than 20 peer leads are excluded, and agents with fewer than 30 comparable leads get no estimate.", "",
          "**What this can and cannot say.** A positive gap means the agent's leads reached High Potential more often than comparable leads handled by others. "
          "It does not separate better selling from a different habit of recording Status, and it only adjusts for mode, location and month. "
          "Leads may also differ in ways these fields do not capture.", "",
          "## All train + validation months", "", all_[cols].round(1).to_markdown(index=False), "",
          "## June-August (routing looked segmented)", "", jja[cols].round(1).to_markdown(index=False), "",
          "## September only (assignment looked closer to random)", "", sep[cols].round(1).to_markdown(index=False), "",
          f"## Robustness: peers exclude {top_agent} (the largest positive outlier)", "",
          "Gaps are relative to peers, so one strong agent lowers every other agent's gap. Dropping them from the peer pool shows how much of the others' gaps came from that.", "",
          no_top[cols].round(1).to_markdown(index=False), ""]

    def verdict(t):
        t = t.dropna(subset=["gap_pp"])
        clear = t[(t.gap_lo > 0) | (t.gap_hi < 0)]
        return t, clear
    t, clear = verdict(all_)
    md += ["## Reading the results", "",
           f"- {len(clear)} of {len(t)} agents with an estimate have an interval that excludes zero over all months: "
           + (", ".join(f"{r.agent} ({r.gap_pp:+.1f} pp)" for r in clear.itertuples()) or "none") + ".",
           (lambda t2, c: f"- With {top_agent} removed from the peer pool, {len(c)} of {len(t2)} remaining agents with an estimate have an interval that excludes zero: "
                          + (", ".join(f"{r.agent} ({r.gap_pp:+.1f} pp)" for r in c.itertuples()) or "none") + ".")(*verdict(no_top)),
           "- Robust in both runs (interval excludes zero with and without the top agent, same sign): "
           + (", ".join(sorted(set(clear.agent) & set(verdict(no_top)[1].agent)
                               - {a for a in set(clear.agent) & set(verdict(no_top)[1].agent)
                                  if np.sign(clear.set_index('agent').loc[a, 'gap_pp']) != np.sign(verdict(no_top)[1].set_index('agent').loc[a, 'gap_pp'])})) or "none") + ".",
           f"- Comparable share of leads: {all_.n_comparable.sum() / all_.n_leads.sum() * 100:.0f}% overall; agents routed to segments few others handled have a low share and a less reliable estimate.", ""]
    (REPO_ROOT / "reports" / "phase6c_agent_analysis.md").write_text("\n".join(md), encoding="utf-8")

    eda.apply_style()
    p = all_[(all_.n_comparable >= MIN_COMPARABLE_FOR_PLOT)].dropna(subset=["gap_pp"]).sort_values("gap_pp")
    fig, ax = plt.subplots(figsize=(8.2, 4.8)); y = np.arange(len(p))
    ax.errorbar(p.gap_pp, y, xerr=[p.gap_pp - p.gap_lo, p.gap_hi - p.gap_pp], fmt="o", color=eda.BLUE, ecolor=eda.INK_2, capsize=3, ms=6, zorder=3)
    ax.scatter(p["unadjusted_high_%"] - df.target_high.mean() * 100, y, marker="x", color=eda.GRAY, s=40, zorder=3, label="Unadjusted (agent rate minus overall)")
    ax.axvline(0, color=eda.GRAY, lw=1); ax.set_yticks(y); ax.set_yticklabels([f"{a}  (n={int(n):,})" for a, n in zip(p.agent, p.n_comparable)])
    ax.set_xlabel("High Potential rate vs comparable leads handled by other agents (percentage points)")
    ax.set_title("Agent gaps after adjusting for mode, location and month"); ax.grid(axis="y", visible=False)
    ax.plot([], [], "o", color=eda.BLUE, label="Adjusted gap, 95% interval"); ax.legend(frameon=False, fontsize=8.5, loc="lower right")
    fig.savefig(REPO_ROOT / "reports/figures/fig21_agent_adjusted_gaps.png", bbox_inches="tight"); plt.close(fig)
    pd.set_option("display.width", 220)
    print(all_[cols].round(1).to_string(index=False)); print(); print(sep[cols].round(1).to_string(index=False))


if __name__ == "__main__":
    main()
