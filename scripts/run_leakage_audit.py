"""Phase 4 leakage / stability audit.

Uses TRAIN (created <= Aug 31) and VALIDATION (September) only. The test period is
never read for any decision here (asserted below).

Outputs: reports/phase4_leakage_audit.md and reports/figures/fig13/fig14.
Usage:   python scripts/run_leakage_audit.py
"""
from __future__ import annotations

import sqlite3
from contextlib import closing
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import Pipeline

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ficzon import eda  # noqa: E402
from ficzon.cleaning import clean_leads  # noqa: E402
from ficzon.data import REPO_ROOT, load_config  # noqa: E402
from ficzon.features import ALL_FEATURES, TIER_A, TIER_B_GROUPS, add_features, make_preprocessor  # noqa: E402
from ficzon.splits import temporal_masks  # noqa: E402

warnings.filterwarnings("ignore")
SEED = 42


def pipe(cols, cfg):
    return Pipeline([("prep", make_preprocessor(cols, cfg["min_category_count"])),
                     ("clf", LogisticRegression(max_iter=2000))])


def boot_auc(y, p, n=300, seed=SEED):
    rng = np.random.default_rng(seed)
    idx = np.arange(len(y)); vals = []
    for _ in range(n):
        b = rng.choice(idx, len(idx))
        if y[b].min() != y[b].max():
            vals.append(roc_auc_score(y[b], p[b]))
    return np.percentile(vals, [2.5, 97.5])


def main() -> None:
    cfg = load_config()
    with closing(sqlite3.connect(str(REPO_ROOT / cfg['paths']['sqlite_db']))) as con:
        df = pd.read_sql_query("SELECT * FROM leads", con, parse_dates=["Created"])
    df = add_features(clean_leads(df, cfg))
    masks = temporal_masks(df["Created"], cfg)
    dev = df[masks["train"] | masks["val"]].copy()          # test rows are dropped here, before any modelling
    assert dev["Created"].max() <= pd.Timestamp(cfg["split"]["val_end"]), "test rows leaked into audit"
    tr, va = dev[masks["train"].loc[dev.index]], dev[masks["val"].loc[dev.index]]
    ytr, yva = tr["target_high"].to_numpy(), va["target_high"].to_numpy()

    md = ["# Phase 4 leakage and stability audit", "",
          "_Generated by `scripts/run_leakage_audit.py`. Train and validation months only; test months untouched._", "",
          f"- Train: {len(tr):,} leads ({tr.Created.min():%Y-%m-%d} to {tr.Created.max():%Y-%m-%d}), High rate {ytr.mean()*100:.1f}%",
          f"- Validation: {len(va):,} leads (September 2018), High rate {yva.mean()*100:.1f}%  <- PR-AUC of a random scorer equals this",
          f"- Test (reserved, not used): {int(masks['test'].sum()):,} leads", ""]

    # 1. Per-feature screen: in-time CV on train vs forward-in-time validation
    cv = StratifiedKFold(5, shuffle=True, random_state=SEED)
    rows = []
    for feat in ALL_FEATURES:
        p = pipe([feat], cfg)
        oof = cross_val_predict(p, tr[[feat]], ytr, cv=cv, method="predict_proba")[:, 1]
        p.fit(tr[[feat]], ytr)
        pv = p.predict_proba(va[[feat]])[:, 1]
        rows.append({"feature": feat, "tier": "A" if feat in TIER_A else "B",
                     "auc_in_time_cv": roc_auc_score(ytr, oof), "auc_forward_val": roc_auc_score(yva, pv),
                     "pr_auc_forward_val": average_precision_score(yva, pv)})
    fs = pd.DataFrame(rows); fs["gap"] = fs.auc_in_time_cv - fs.auc_forward_val
    fs = fs.sort_values("auc_forward_val", ascending=False)
    md += ["## 1. Single-feature screen", "",
           "In-time CV AUC (random folds inside train) vs forward AUC (fit on train, score September). A big gap means the "
           "feature's signal does not carry forward in time. A near-perfect AUC would signal outcome leakage.", "",
           fs.round(3).to_markdown(index=False), ""]

    # 2. Group ablation
    sets = {"Tier A only (source + creation time)": list(TIER_A)}
    for g, cols in TIER_B_GROUPS.items():
        sets[f"A + {g}"] = TIER_A + cols
    sets["A + all Tier B"] = list(ALL_FEATURES)
    sets["All Tier B without Sales_Agent, flags, contact history"] = TIER_A + ["Product", "Location", "Delivery_Mode"]
    rows = []
    for name, cols in sets.items():
        p = pipe(cols, cfg).fit(tr[cols], ytr)
        pv = p.predict_proba(va[cols])[:, 1]
        lo, hi = boot_auc(yva, pv)
        rows.append({"feature_set": name, "n_features": len(cols), "roc_auc": roc_auc_score(yva, pv), "ci_lo": lo, "ci_hi": hi,
                     "pr_auc": average_precision_score(yva, pv)})
    ab = pd.DataFrame(rows)
    md += ["## 2. Feature-group ablation (logistic regression, fit on train, scored on September)", "",
           f"Random-scorer PR-AUC = {yva.mean():.3f}. ROC-AUC 95% interval is a bootstrap over validation rows.", "",
           ab.round(3).to_markdown(index=False), ""]

    # 3. Routing / dependency checks
    g = {c: eda.group_levels(dev[c], 30) for c in ["Sales_Agent", "Product", "Location", "Delivery_Mode", "Source_clean"]}
    route = pd.Series({c: eda.cramers_v(g["Sales_Agent"], g[c]) for c in ["Product", "Location", "Delivery_Mode", "Source_clean"]})
    dev["month"] = dev["Created"].dt.strftime("%Y-%m")
    drift = pd.Series({c: eda.cramers_v(eda.group_levels(dev[c], 30) if c in g else dev[c], dev["month"])
                       for c in ["Sales_Agent", "Product", "Location", "Delivery_Mode", "Source_clean", "email_valid", "mobile_missing"]})
    md += ["## 3. Routing and drift checks (train + validation)", "",
           "Cramer's V of Sales_Agent with other fields (high = leads look routed to agents by that field):", "",
           route.round(3).rename("V").to_frame().to_markdown(), "",
           "Cramer's V of each field with creation month (high = distribution shifts over time):", "",
           drift.round(3).rename("V").to_frame().to_markdown(), ""]

    # 4. Cleaning impact
    raw_src = df["Source"].nunique(); clean_src = df["Source_clean"].nunique()
    md += ["## 4. Cleaning impact", "",
           f"- Rows before / after cleaning: {len(df):,} / {len(df):,} (none dropped)",
           f"- Distinct Source labels: {raw_src} raw -> {clean_src} after consolidation",
           f"- Missing values kept: Product {int(df.Product.isna().sum())}, Source {int(df.Source.isna().sum())}, "
           f"Sales_Agent {int(df.Sales_Agent.isna().sum())}, Location {int(df.Location.isna().sum())} (imputed as 'Unknown' inside the pipeline)",
           f"- prior_contact_leads: median {df.prior_contact_leads.median():.0f}, max {df.prior_contact_leads.max():.0f}, "
           f"{(df.prior_contact_leads==0).mean()*100:.1f}% zero", ""]

    # 5. Time-artifact checks (train + validation only)
    from scipy.stats import spearmanr
    by_m = dev.groupby("month").agg(leads=("lead_id", "size"), pct_mobile_missing=("mobile_missing", "mean"),
                                    pct_email_valid=("email_valid", "mean"), median_prior_contact_leads=("prior_contact_leads", "median"))
    by_m[["pct_mobile_missing", "pct_email_valid"]] = (by_m[["pct_mobile_missing", "pct_email_valid"]] * 100).round(1)
    rho = spearmanr(dev["Created"].astype("int64"), dev["prior_contact_leads"]).statistic
    md += ["## 5. Time-artifact checks", "",
           "A feature whose value is a function of calendar time cannot be trusted to generalize to later months.", "",
           by_m.to_markdown(), "",
           f"Spearman correlation of prior_contact_leads with creation time: **{rho:.3f}**", ""]

    # 6. Do Product / Location / Delivery_Mode describe one low-engagement segment?
    quiet = ["Junk Lead", "Not Responding"]
    def mix(mask, name):
        s = dev[mask]
        return {"segment": name, "n": len(s), "pct_junk_or_not_responding": round(s.Status.isin(quiet).mean() * 100, 1),
                "pct_high": round(s.target_high.mean() * 100, 1)}
    seg = pd.DataFrame([mix(dev.index == dev.index, "All leads"), mix(dev.Location == "Other Locations", "Location = Other Locations"),
                        mix(dev.Location == "Bangalore", "Location = Bangalore"), mix(dev.Product == "P15", "Product = P15"),
                        mix(dev.Delivery_Mode == "Mode-5", "Delivery_Mode = Mode-5"), mix(dev.Delivery_Mode == "Mode-1", "Delivery_Mode = Mode-1")])
    p15 = dev.Product == "P15"
    md += ["## 6. Segment overlap: Product, Location, Delivery_Mode", "", seg.to_markdown(index=False), "",
           f"- Share of Product P15 leads that are also 'Other Locations': {((p15) & (dev.Location == 'Other Locations')).sum() / p15.sum() * 100:.1f}%",
           f"- Share of Product P15 leads that are also Mode-5: {((p15) & (dev.Delivery_Mode == 'Mode-5')).sum() / p15.sum() * 100:.1f}%",
           f"- Share of Mode-5 leads that are also 'Other Locations': {((dev.Delivery_Mode == 'Mode-5') & (dev.Location == 'Other Locations')).sum() / (dev.Delivery_Mode == 'Mode-5').sum() * 100:.1f}%",
           "", "These three fields overlap heavily, so they are not independent signals, and each is concentrated in leads that "
           "never engage (Junk / Not Responding). Whether they are known at creation or filled in after contact decides whether "
           "they are legitimate predictors or a restatement of the outcome. This needs the project owner.", ""]

    (REPO_ROOT / "reports" / "phase4_leakage_audit.md").write_text("\n".join(md), encoding="utf-8")

    # Figures
    eda.apply_style()
    a = ab.sort_values("roc_auc")
    fig, ax = plt.subplots(figsize=(8.5, 4.6)); y = np.arange(len(a))
    ax.errorbar(a.roc_auc, y, xerr=[a.roc_auc - a.ci_lo, a.ci_hi - a.roc_auc], fmt="o", color=eda.BLUE, ecolor=eda.INK_2, capsize=3, ms=6)
    ax.axvline(0.5, color=eda.GRAY, ls="--", lw=1.2); ax.set_yticks(y); ax.set_yticklabels(a.feature_set, fontsize=8.5)
    for yi, v in zip(y, a.roc_auc): ax.text(v, yi + 0.22, f"{v:.3f}", ha="center", fontsize=8, color=eda.INK_2)
    ax.set_xlabel("Validation ROC-AUC (September)  -  whiskers: 95% bootstrap interval; dashed = random")
    ax.set_title("What each feature group adds (fit on train, scored on September)"); ax.grid(axis="y", visible=False)
    fig.savefig(REPO_ROOT / "reports/figures/fig13_feature_group_ablation.png", bbox_inches="tight"); plt.close(fig)

    f2 = fs.sort_values("auc_forward_val"); y = np.arange(len(f2))
    fig, ax = plt.subplots(figsize=(8.5, 5.2))
    ax.hlines(y, f2.auc_forward_val, f2.auc_in_time_cv, color=eda.GRAY, lw=2)
    ax.scatter(f2.auc_in_time_cv, y, color=eda.GRAY, s=45, label="In-time CV (random folds in train)", zorder=3)
    ax.scatter(f2.auc_forward_val, y, color=eda.BLUE, s=45, label="Forward (train -> September)", zorder=3)
    ax.axvline(0.5, color=eda.GRAY, ls="--", lw=1); ax.set_yticks(y); ax.set_yticklabels(f2.feature, fontsize=8.5)
    ax.set_xlabel("Single-feature ROC-AUC"); ax.set_title("Does each feature's signal carry forward in time?")
    ax.legend(frameon=False, fontsize=8.5, loc="lower right"); ax.grid(axis="y", visible=False)
    fig.savefig(REPO_ROOT / "reports/figures/fig14_feature_stability.png", bbox_inches="tight"); plt.close(fig)
    print("done")


if __name__ == "__main__":
    main()
